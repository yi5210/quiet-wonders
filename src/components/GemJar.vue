// 記錄最近封存月份的最後一天
// 用來避免自動補漏重新建立已封存日期的光珠
const lastArchivedDate = ref(
  localStorage.getItem('store_last_archived_date') || ''
)

function createHappyGem(dateStr, timestamp) {
  const randomOffsetX = Math.floor(Math.random() * 9) - 4
  const randomOffsetY = Math.floor(Math.random() * 7) - 3

  return {
    id: timestamp,
    date: dateStr,
    color: '#FFFFFF',
    note: '這天忘了寫，是因為正忙著快樂吧！',
    offsetX: randomOffsetX,
    offsetY: randomOffsetY,
    isAutoGenerated: true
  }
}

function checkMissedDays() {
  if (gems.value.length === 0) return

  const existingDates = new Set(
    gems.value.map(g => g.date).filter(Boolean)
  )

  const sortedDates = Array.from(existingDates).sort()
  if (sortedDates.length === 0) return

  const firstGemDate = parseLocalDate(sortedDates[0])
  const currentDate = parseLocalDate(todayStr)

  const sevenDaysAgo = new Date(
    currentDate.getTime() - 7 * 24 * 60 * 60 * 1000
  )

  // 補漏起點不可早於：
  // 1. 最早一顆光珠的日期
  // 2. 最近七天的範圍
  // 3. 最近一次封存月份的最後一天
  const boundaryDate = lastArchivedDate.value
    ? parseLocalDate(lastArchivedDate.value)
    : new Date(0)

  let loopDate = new Date(
    Math.max(
      firstGemDate.getTime(),
      sevenDaysAgo.getTime(),
      boundaryDate.getTime()
    )
  )

  // 從起點的隔天開始檢查
  loopDate = new Date(loopDate.getTime() + 24 * 60 * 60 * 1000)

  while (loopDate < currentDate) {
    const checkDateStr = formatDate(loopDate)

    // 再次確認日期沒有落在封存邊界內
    const isBeforeOrOnArchivedBoundary =
      lastArchivedDate.value &&
      checkDateStr <= lastArchivedDate.value

    if (
      !isBeforeOrOnArchivedBoundary &&
      !existingDates.has(checkDateStr)
    ) {
      const newGem = createHappyGem(
        checkDateStr,
        loopDate.getTime()
      )

      gems.value.push(newGem)
      existingDates.add(checkDateStr)
    }

    loopDate = new Date(
      loopDate.getTime() + 24 * 60 * 60 * 1000
    )
  }
  gems.value.sort((a, b) => (a.date || '').localeCompare(b.date || ''))
}

// 頁面初始化時檢查漏掉的日期
checkMissedDays()

