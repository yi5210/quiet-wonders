// ==========================================
// 1. 日期與時區處理工具函式
// ==========================================

function formatDate(date) {
  const year = date.getFullYear()
  const month = String(date.getMonth() + 1).padStart(2, '0')
  const day = String(date.getDate()).padStart(2, '0')
  return `${year}-${month}-${day}`
}

function getLogicalDate(date = new Date()) {
  const adjusted = new Date(date.getTime() - 2 * 60 * 60 * 1000)
  return formatDate(adjusted)
}

const todayStr = getLogicalDate()

function parseLocalDate(dateStr) {
  const [year, month, day] = dateStr.split('-').map(Number)
  return new Date(year, month - 1, day, 12, 0, 0)
}

function isLastDayOfMonth(dateStr) {
  const [year, month, day] = dateStr.split('-').map(Number)
  const lastDay = new Date(year, month, 0).getDate()
  return day === lastDay
}

function isFirstDayOfMonth(dateStr) {
  const [, , day] = dateStr.split('-').map(Number)
  return day === 1
}

function getPreviousMonthStr(dateStr) {
  const [year, month] = dateStr.split('-').map(Number)
  const prevDate = new Date(year, month - 2, 1)
  const prevYear = prevDate.getFullYear()
  const prevMonth = String(prevDate.getMonth() + 1).padStart(2, '0')
  return `${prevYear}-${prevMonth}`
}

// 取得指定月份的最後一天
function getMonthEndDate(monthStr) {
  const [year, month] = monthStr.split('-').map(Number)
  return formatDate(new Date(year, month, 0))
}

