const hasCollectedToday = computed(() => {
  const hasManualGem = gems.value.some(
    g => g.date === todayStr && !g.isAutoGenerated
  )

  const archivedToday = lastArchivedDate.value === todayStr

  return hasManualGem || archivedToday
})

