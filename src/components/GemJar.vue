// 4. 月度色卡統計與極光漸層生成
// ==========================================

const showMonthlyCard = ref(false)
const isShootingStars = ref(false)
const cardMonthTarget = ref(todayStr.slice(0, 7))

const showAlbum = ref(false)
const archivedCards = ref(
  JSON.parse(
    localStorage.getItem('store_archived_cards') || '[]'
