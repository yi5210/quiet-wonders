const todayNote = ref('')
const activeGem = ref(null)
const filterDate = ref('')

function isDimmed(gem) {
  if (!filterDate.value) return false
  return gem.date !== filterDate.value
}

function isHighlighted(gem) {
  if (!filterDate.value) return false
  return gem.date === filterDate.value
}

function resetFilter() {
  filterDate.value = ''
}

function selectColor(color) {
  selectedColor.value = color
}

function openGem(gem) {
  activeGem.value = gem
}

function closeGem() {
  activeGem.value = null
}

function editGem() {
  const newNote = prompt(
    '修改你的美好小事：',
    activeGem.value.note
  )

  if (newNote && newNote.trim() !== '') {
    activeGem.value.note = newNote.trim()
  }
}

function deleteGem() {
  if (confirm('確定要撤回這道微光嗎？')) {
    gems.value = gems.value.filter(
      g => g.id !== activeGem.value.id
    )

    closeGem()
  }
}

function addGem() {
  if (hasCollectedToday.value) {
    alert('今天的微光已經採集過了，明天再來吧！')
    return
  }

  if (todayNote.value.trim() === '') {
    alert('請先寫下一件今天的美好小事喔！')
    return
  }

  const randomOffsetX = Math.floor(Math.random() * 9) - 4
  const randomOffsetY = Math.floor(Math.random() * 7) - 3

  const newGem = {
    id: Date.now(),
    date: todayStr,
    color: selectedColor.value,
    note: todayNote.value.trim(),
    offsetX: randomOffsetX,
    offsetY: randomOffsetY
  }

  gems.value.push(newGem)
  todayNote.value = ''

  if (isLastDayOfMonth(todayStr)) {
    triggerShootingStarsRitual(todayStr.slice(0, 7))
  } else {
    isGlowing.value = true

    setTimeout(() => {
      isGlowing.value = false
    }, 1000)
  }
}

