)

const selectedAlbumCard = ref(null)

const canClaimPreviousMonth = computed(() => {
  if (!isFirstDayOfMonth(todayStr)) return false

  const prevMonth = getPreviousMonthStr(todayStr)

  // 上個月仍有光珠，且尚未完成封存，才顯示回顧入口
  const hasPreviousMonthGems = gems.value.some(
    g => g.date && g.date.startsWith(prevMonth)
  )

  const alreadyArchived = archivedCards.value.some(
    card => card.month === prevMonth
  )

  return hasPreviousMonthGems && !alreadyArchived
})

function openPreviousMonthCard() {
  cardMonthTarget.value = getPreviousMonthStr(todayStr)
  showMonthlyCard.value = true
}

const targetMonthGems = computed(() => {
  return gems.value.filter(
    g => g.date && g.date.startsWith(cardMonthTarget.value)
  )
})

const colorStats = computed(() => {
  const total = targetMonthGems.value.length
  if (total === 0) return []

  const counts = {}

  targetMonthGems.value.forEach(g => {
    counts[g.color] = (counts[g.color] || 0) + 1
  })

  return Object.entries(counts)
    .map(([color, count]) => ({
      color,
      count,
      label: labelOf(color),
      ratio: Math.round((count / total) * 100)
    }))
    .sort((a, b) => b.count - a.count)
})

const monthlyGradientStyle = computed(() => {
  const stats = colorStats.value

  if (stats.length === 0) {
    return {
      background: 'linear-gradient(135deg, #2d3748 0%, #1a202c 100%)'
    }
  }

  const dominant = stats[0]

  const anchorPoints = [
    '25% 25%',
    '80% 75%',
    '75% 25%',
    '20% 80%',
    '50% 50%'
  ]

  const radialLayers = stats.map((item, idx) => {
    const pos = anchorPoints[idx % anchorPoints.length]

    const renderColor =
      item.color.toLowerCase() === '#ffffff'
        ? 'rgba(255, 255, 255, 0.9)'
        : item.color

    const radius = Math.min(
      90,
      Math.max(50, item.ratio + 30)
    )

    return `radial-gradient(circle at ${pos}, ${renderColor} 0%, rgba(255, 255, 255, 0) ${radius}%)`
  })

  return {
    backgroundImage: radialLayers.join(', '),
    backgroundColor: dominant.color
  }
})

function getCardGradientStyle(card) {
  if (!card.stats || card.stats.length === 0) {
    return { background: '#2d3748' }
  }

  const anchorPoints = [
    '25% 25%',
    '80% 75%',
    '75% 25%',
    '20% 80%',
    '50% 50%'
  ]

  const radialLayers = card.stats.map((item, idx) => {
    const pos = anchorPoints[idx % anchorPoints.length]

    const renderColor =
      item.color.toLowerCase() === '#ffffff'
        ? 'rgba(255, 255, 255, 0.85)'
        : item.color

    const radius = Math.min(
      110,
      Math.max(60, item.ratio + 45)
    )

    return `radial-gradient(circle at ${pos}, ${renderColor} 0%, rgba(255, 255, 255, 0) ${radius}%)`
  })

  return {
    backgroundImage: radialLayers.join(', '),
    backgroundColor: card.dominantColor || card.stats[0].color
  }
}

function triggerShootingStarsRitual(
  monthTarget = todayStr.slice(0, 7)
) {
  cardMonthTarget.value = monthTarget

  if (targetMonthGems.value.length === 0) {
    showMonthlyCard.value = true
    return
  }

  isShootingStars.value = true

  const totalDuration = 550 + gems.value.length * 80 + 750

  setTimeout(() => {
    isShootingStars.value = false
    showMonthlyCard.value = true
  }, totalDuration)
}

