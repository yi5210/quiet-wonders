function sealMonthlyCard() {
  const monthTarget = cardMonthTarget.value

  if (!monthTarget || colorStats.value.length === 0) {
    showMonthlyCard.value = false
    return
  }

  // 先建立獨立快照，避免清空光珠後影響月卡資料
  const cardSnapshot = {
    month: monthTarget,
    totalGems: targetMonthGems.value.length,
    stats: colorStats.value.map(item => ({ ...item })),
    dominantColor: colorStats.value[0]?.color || '#ffffff',
    sealedAt: new Date().toISOString()
  }

  // 若該月份已存在相簿，就更新原本的月卡；否則新增一張
  const existingIndex = archivedCards.value.findIndex(
    card => card.month === monthTarget
  )

  if (existingIndex !== -1) {
    archivedCards.value[existingIndex] = cardSnapshot
  } else {
    archivedCards.value.unshift(cardSnapshot)
  }

  // 依月份新到舊排列
  archivedCards.value.sort((a, b) => {
    return b.month.localeCompare(a.month)
  })

  // 先保存月卡資料
  localStorage.setItem(
    'store_archived_cards',
    JSON.stringify(archivedCards.value)
  )

  // 將封存邊界記錄為該月份的最後一天
  // 只允許邊界往後推進，避免舊月份封存時覆蓋較新的日期
  const monthEndDate = getMonthEndDate(monthTarget)

  if (
    !lastArchivedDate.value ||
    monthEndDate > lastArchivedDate.value
  ) {
    lastArchivedDate.value = monthEndDate

    localStorage.setItem(
      'store_last_archived_date',
      lastArchivedDate.value
    )
  }

  // 只清除這個月份的光珠，其他月份與無日期資料都保留
  gems.value = gems.value.filter(g => {
    return !g.date || !g.date.startsWith(monthTarget)
  })

  // 立即同步儲存清空後的光珠資料
  localStorage.setItem(
    'store_gems',
    JSON.stringify(gems.value)
  )

  // 關閉月卡視窗
  showMonthlyCard.value = false
}

