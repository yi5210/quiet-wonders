// 6. html-to-image 圖片匯出
// ==========================================

const currentCardRef = ref(null)
const detailCardRef = ref(null)
const isExporting = ref(false)

async function exportCardAsImage(
  elementRef,
  filenamePrefix = 'mood-card'
) {
  if (!elementRef || isExporting.value) return

  let actionArea = null
  let cardMeta = null
  let originalDisplay = ''
  let originalPaddingBottom = ''

  try {
    isExporting.value = true

    actionArea = elementRef.querySelector('.card-modal-actions')
    cardMeta = elementRef.querySelector('.card-meta')

    // 暫時隱藏按鈕，避免匯出時將操作按鈕一起存進圖片
    if (actionArea) {
      originalDisplay = actionArea.style.display
      actionArea.style.display = 'none'
    }

    // 調整底部間距，避免隱藏按鈕後留下過大的空白
    if (cardMeta) {
      originalPaddingBottom = cardMeta.style.paddingBottom
      cardMeta.style.paddingBottom = '8px'
    }

    const image = await toPng(elementRef, {
      pixelRatio: 2,
      cacheBust: true,
      backgroundColor: '#ffffff'
    })

    const link = document.createElement('a')
    link.href = image
    link.download = `${filenamePrefix}-${Date.now()}.png`

    document.body.appendChild(link)
    link.click()
    document.body.removeChild(link)
  } catch (error) {
    console.error('色卡匯出失敗：', error)
    alert('匯出圖片時發生問題，請稍候再試！')
  } finally {
    // 不論匯出成功或失敗，都恢復原本的畫面樣式
    if (actionArea) {
      actionArea.style.display = originalDisplay
    }

    if (cardMeta) {
      cardMeta.style.paddingBottom = originalPaddingBottom
    }

    isExporting.value = false
  }
}
